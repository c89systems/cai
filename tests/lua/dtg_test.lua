local cai = require('cai')
local value = cai.dtg_parse('091630tjul11')
assert(value.day == 9 and value.year == 11 and value.month == 7)
assert(value.offset_known and value.offset_seconds == -25200)
assert(cai.dtg_format(value) == '091630TJUL11')
assert(cai.dtg_zone(19800) == 'E*')
assert(cai.dtg_zone(46800) == 'M*')
assert(cai.dtg_zone(20700) == 'J')
assert(not cai.dtg_parse('021230JNOV26').offset_known)
assert(cai.dtg_format_time(1793622600, 1793622600, true) == '021230Z')
assert(cai.dtg_parse('311230AFEB26') == nil)
assert(cai.dtg_parse('021230\0junk') == nil)
assert(cai.dtg_zone(86400) == nil)
assert(cai.dtg_format({day = 4294967298}) == nil)
assert(cai.dtg_format({day = 2, has_zone = true, zone = 'J\0Z'}) == nil)
local record = assert(cai.execution_record([[{"kind":"tool.failed","session_id":"dtg","timestamp_ns":1793622600123456789,"utc_offset_seconds":20700,"offset":0,"final":true,"line_start":true,"data":"original time"}]]))
assert(record.timestamp_ns == 1793622600123456789)
assert(record.utc_offset_seconds == 20700)
